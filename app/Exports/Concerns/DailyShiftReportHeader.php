<?php

namespace App\Exports\Concerns;

use App\Models\Company;
use Carbon\Carbon;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Facades\Auth;
use PhpOffice\PhpSpreadsheet\RichText\RichText;
use PhpOffice\PhpSpreadsheet\Worksheet\Drawing;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

/**
 * Shared by the daily shift production reports (Key Metrics + Rehandling):
 * company logo at A2, a report info block (periods, generated on/by) on
 * rows 2-5, and the exact shift-start window filter.
 */
trait DailyShiftReportHeader
{
    protected ?Carbon $generatedAt = null;

    public function drawings()
    {
        $drawing = new Drawing();
        $company = $this->reportCompany();
        $path = public_path('/images/uploads/logo.png');

        if ($company) {
            $drawing->setName($company->name);
            $drawing->setDescription($company->name . ' Logo');

            if (filled($company->logo) && file_exists(public_path('/images/uploads/' . $company->logo))) {
                $path = public_path('/images/uploads/' . $company->logo);
            }
        }

        $drawing->setPath($path);
        $drawing->setHeight(90);
        $drawing->setCoordinates('A2');

        return $drawing;
    }

    /** Signed-in user's company, else the first active company (scheduled email run). */
    protected function reportCompany(): ?Company
    {
        return Auth::user()->employee->company
            ?? Company::where('is_active', true)->orderBy('created_at', 'asc')->first();
    }

    protected function reportGeneratedBy(): string
    {
        $user = Auth::user();

        return $user ? trim($user->name . ' ' . $user->surname) : 'System (Daily Reports)';
    }

    /**
     * Writes "Label: value" lines starting at $col, row 2 down. Each line sits in
     * one cell and overflows to the right, so it doesn't depend on column widths.
     *
     * @param array<string, string> $lines
     */
    protected function writeReportInfo(Worksheet $sheet, string $col, array $lines): void
    {
        $this->generatedAt ??= now();

        $lines += [
            'Generated On' => $this->generatedAt->format('d M Y H:i'),
            'Generated By' => $this->reportGeneratedBy(),
        ];

        $row = 2;
        foreach ($lines as $label => $value) {
            $text = new RichText();
            $text->createTextRun($label . ': ')->getFont()->setBold(true);
            $text->createText((string) $value);

            $sheet->setCellValue("{$col}{$row}", $text);
            $sheet->getStyle("{$col}{$row}")->getAlignment()->setWrapText(false);
            $row++;
        }
    }

    protected function formatWindow(Carbon $from, Carbon $to): string
    {
        return $from->format('d M Y H:i') . ' - ' . $to->format('d M Y H:i');
    }

    /**
     * Shifts that started inside [$from, $to]. shift_start_time is a string:
     * "Y-m-d\TH:i" from the shift form, or just "H:i:s" from imports (the day
     * is then in shifts.date), so compare on one normalised "Y-m-d\TH:i" value.
     */
    protected function whereShiftStartBetween(Builder $q, Carbon $from, Carbon $to): Builder
    {
        $table = $q->getModel()->getTable();
        $start = "`{$table}`.`shift_start_time`";
        $date = "`{$table}`.`date`";

        $normalised = "CASE WHEN {$start} LIKE '____-__-__%' "
            . "THEN REPLACE(LEFT({$start}, 16), ' ', 'T') "
            . "ELSE CONCAT({$date}, 'T', LEFT({$start}, 5)) END";

        return $q->whereRaw(
            "{$normalised} BETWEEN ? AND ?",
            [$from->format('Y-m-d\TH:i'), $to->format('Y-m-d\TH:i')]
        );
    }
}
